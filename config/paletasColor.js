const normal = (t) => String(t ?? '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().toLowerCase()

// Por nombre, sin importar acentos ni mayúsculas
const paletaPorNombre = (nombre) => PALETAS.find(p => normal(p.name) === normal(nombre)) ?? null

// La paleta cuyos 4 colores coinciden con los de la invitación (si alguna)
const paletaDeColores = (colors = {}) => PALETAS.find(p =>
  ['primary', 'secondary', 'accent', 'actions'].every(k => normal(p[k]) === normal(colors[k]))) ?? null

// Para los prompts: nombre (palabras clave)
const catalogoParaPrompt = () => PALETAS.map(p => `${p.name} (${p.keywords.join(', ')})`).join('; ')

module.exports = { PALETAS, paletaPorNombre, paletaDeColores, catalogoParaPrompt }
